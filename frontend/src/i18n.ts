export function translator(language: string) {
  return (text: string) =>
    language === "en"
      ? english[text] ||
        (english[text.trim()]
          ? text.replace(text.trim(), english[text.trim()])
          : text)
      : text;
}
export function useTranslation() {
  return translator(usePreferences().preferences.language);
}
